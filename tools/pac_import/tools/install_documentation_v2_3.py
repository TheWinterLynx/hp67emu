"""Package reviewed PAC/owner PDFs and add presentation-only documentation access."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import tempfile

HERE=Path(__file__).resolve().parent

def digest(path):
    h=hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda:stream.read(1024*1024),b''):h.update(block)
    return h.hexdigest()

def validate_pdf(path,expected=None):
    with path.open('rb') as stream:
        if stream.read(5)!=b'%PDF-':raise ValueError(f'Not a PDF: {path}')
    actual=digest(path)
    if expected is not None and actual!=expected:raise ValueError(f'PDF hash mismatch: {path}')
    return actual

def patch_sources(repo,module):
    app=repo/'src/app.rs';text=app.read_text(encoding='utf-8')
    if 'crate::documentation::help_menu(ui);' not in text:
        marker='            egui::menu::bar(ui, |ui| {'
        if text.count(marker)!=1:raise ValueError('Application menu anchor changed')
        text=text.replace(marker,marker+'\n                crate::documentation::help_menu(ui);',1)
    if 'crate::documentation::show(ctx);' not in text:
        marker='        self.show_program_library(ctx);'
        if text.count(marker)!=1:raise ValueError('Application window anchor changed')
        text=text.replace(marker,marker+'\n        crate::documentation::show(ctx);',1)
    if 'crate::documentation::pack_manual_button(ui, entry.pack, entry.source_pdf);' not in text:
        marker='ui.label(format!("Pack: {}", entry.pack));'
        if text.count(marker)!=3:raise ValueError('Library detail anchors changed')
        text=text.replace(marker,marker+'\n                        crate::documentation::pack_manual_button(ui, entry.pack, entry.source_pdf);')
    main=repo/'src/main.rs';maintext=main.read_text(encoding='utf-8')
    if 'mod documentation;' not in maintext:
        if 'mod app;' not in maintext:raise ValueError('Binary module anchor changed')
        maintext=maintext.replace('mod app;','mod app;\nmod documentation;',1)
    index=repo/'index.html';html=index.read_text(encoding='utf-8')
    if 'href="documentation"' not in html:
        if '    <style>' not in html:raise ValueError('Trunk document anchor changed')
        html=html.replace('    <style>','    <link data-trunk rel="copy-dir" href="documentation" />\n    <style>',1)
    return {app:text,main:maintext,index:html,repo/'src/documentation.rs':module}

def install(repo,work,check=False):
    plan=json.loads((work/'plan.json').read_text(encoding='utf-8'))
    base=repo/'programs/HP67/ImportedPACs'
    manifest=json.loads((base/'import_manifest.json').read_text(encoding='utf-8'))
    module=(HERE.parent/'templates/documentation.rs').read_text(encoding='utf-8')
    expected=re.findall(r'file: "([^"]+)"',module)
    sources={item['file']:(base/'manuals'/item['file'],item['sha256']) for item in manifest['pdfs'].values()}
    if len(sources)!=11:raise ValueError('Expected eleven reviewed PAC PDFs')
    sources['hp67-oh-es.pdf']=(Path(plan['source_root'])/'hp67-oh-es.pdf',None)
    if set(sources)!=set(expected):raise ValueError('Manual catalog and source PDFs disagree')
    output=repo/'documentation'
    hashes={}
    # Validate all twelve source files and source patch anchors before writing anything.
    for name,(source,sha) in sources.items():
        hashes[name]=validate_pdf(source,sha)
        target=output/name
        if target.exists() and digest(target)!=hashes[name]:raise ValueError(f'Different document already installed: {target}')
    changes=patch_sources(repo,module)
    if check:
        print('DOCUMENTATION PREFLIGHT OK: all twelve source PDFs and patch anchors validated.',flush=True)
        return
    with tempfile.TemporaryDirectory(prefix='hp67-docs-') as directory:
        stage=Path(directory)
        for i,(name,(source,_)) in enumerate(sources.items(),1):
            with source.open('rb') as src,(stage/name).open('wb') as dst:shutil.copyfileobj(src,dst,1024*1024)
            validate_pdf(stage/name,hashes[name]);print(f'Documentation {i}/12: {name}',flush=True)
        output.mkdir(parents=True,exist_ok=True)
        for name in sources:
            if not (output/name).exists():
                with (stage/name).open('rb') as src,(output/name).open('wb') as dst:shutil.copyfileobj(src,dst,1024*1024)
                validate_pdf(output/name,hashes[name])
        changes[output/'available.rs']='// Validated packaged documents; generated by install_documentation_v2_3.py.\nconst PACKAGED_PDFS: &[&str] = &[\n'+''.join(f'    "{name}",\n' for name in sorted(sources))+'];\n'
        for path,text in changes.items():path.write_text(text,encoding='utf-8')
    doc=repo/'docs/files/src/documentation.rs.md';doc.parent.mkdir(parents=True,exist_ok=True)
    doc.write_text('# `src/documentation.rs`\n\n## Purpose\n\nExpose the calculator handbook and complete PAC manuals through Help and selected-card details.\n\n## Why it exists\n\nReaders need the application instructions alongside the magnetic media.\n\n## Relationships\n\nCalled by app.rs; uses the desktop PDF viewer or packaged browser URLs.\n\n## Responsibilities\n\nPresent full manual names, disable unavailable PDFs, keep external document opening separate from emulation.\n\n## Implementation\n\nDesktop lookup checks the executable documentation folder and development checkout. PDF signatures are checked. Availability is cached in UI memory and refreshed explicitly; no per-frame disk reads or PDF decoding in the machine loop. Browser availability comes from documentation/available.rs and Trunk copies the folder.\n',encoding='utf-8')
    for name in ['src/app.rs','src/main.rs']:
        p=repo/'docs/files'/Path(name+'.md')
        addition='\n\nDocumentation v2.3 adds Help/Documentation and selected-PAC PDF access, separate from machine execution.\n'
        text=p.read_text(encoding='utf-8')
        if addition not in text:p.write_text(text+addition,encoding='utf-8')
    print('DOCUMENTATION OK: calculator handbook + 11 PAC PDFs; desktop and web access installed.',flush=True)

def main():
    p=argparse.ArgumentParser();p.add_argument('--repo',type=Path,required=True);p.add_argument('--work',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args();install(a.repo.resolve(),a.work.resolve(),a.check)
if __name__=='__main__':main()
