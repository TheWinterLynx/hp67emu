#[derive(Clone, Copy)]
pub(crate) struct Transform {
    pub(crate) origin: Pos2,
    pub(crate) scale: f32,
}
impl Transform {
    pub(crate) fn s(self, v: f32) -> f32 {
        v * self.scale
    }
    pub(crate) fn pos(self, x: f32, y: f32) -> Pos2 {
        Pos2::new(
            self.origin.x + x * self.scale,
            self.origin.y + y * self.scale,
        )
    }
    pub(crate) fn rect(self, x: f32, y: f32, w: f32, h: f32) -> Rect {
        Rect::from_min_size(self.pos(x, y), Vec2::new(self.s(w), self.s(h)))
    }
    pub(crate) fn translated_y(self, dy: f32) -> Self {
        Self {
            origin: Pos2::new(self.origin.x, self.origin.y + dy * self.scale),
            scale: self.scale,
        }
    }
}

pub(crate) fn scale_for(available: Vec2) -> f32 {
    if available.x <= 0.0 || available.y <= 0.0 {
        0.0
    } else {
        (available.x / DESIGN_W).min(available.y / DESIGN_H)
    }
}
